const UNSUITABLE_MEANINGS = ['嫉妬','望みのない愛','失われた愛','私を忘れてください','別れの春','気まぐれ'];
const SETTINGS = { enableSeasonal: false }; // 販売確認後にtrueに変更。trueなら該当月のみ候補。
function getAnswerScores(mode, answers) {
  const scores = {};
  for(let i=1;i<10;i++) {
    const chosen=answers[i];
    if(!Number.isInteger(chosen) || chosen<0 || chosen>4) throw Error(`Q${i+1}の回答がありません`);
    const tags=ANSWER_TAGS[mode][i-1][chosen];
    const each=QUESTION_WEIGHTS[i-1]/tags.length;
    for(const tag of tags) scores[tag]=(scores[tag]||0)+each;
  }
  return scores;
}
function flowerTags(flower) {
  return [...new Set(flower.meaning.split('・').flatMap(word=>MEANING_TAGS[word]||[]))];
}
function eligible(flower,month) {
  if(flower.meaning.split('・').some(word=>UNSUITABLE_MEANINGS.includes(word))) return false;
  return !flower.seasonal || (SETTINGS.enableSeasonal && flower.month===month);
}
// 各花言葉の語数で点数が膨らまないよう、テーマ一致を正規化。
// Q5の願いは重視するが、他の回答を覆すほどのボーナスは与えない。
const Q5_KEYWORDS = [
  ['夢かなう','成功','希望'],
  ['幸福','幸せ','喜び','祝福'],
  ['癒し'],
  ['門出','新しい一歩','芽吹き'],
  ['思い出','記憶','絆']
];
const RELATION_TAGS = {
  gift: [ ['愛','誠実'], ['友情','絆','感謝'], ['感謝','温もり'], ['尊敬','誇り'], [], [] ],
  self: [[],[],[],[],[],[]]
};
function rankFlowers(mode,answers,month=new Date().getMonth()+1) {
  const scores=getAnswerScores(mode,answers);
  const q5=ANSWER_TAGS[mode][3][answers[4]];
  const q5Words=Q5_KEYWORDS[answers[4]]||[];
  const relation=RELATION_TAGS[mode][answers[0]]||[];
  const ranked=FLOWERS.map((flower,index)=>{
    const tags=flowerTags(flower);
    const matched=tags.filter(tag=>scores[tag]>0).sort((a,b)=>scores[b]-scores[a]||a.localeCompare(b,'ja'));
    // 最高の一致点に加え、ほかの一致テーマも評価。タグの多さだけでは勝てない。
    const matches=matched.map(tag=>scores[tag]).sort((a,b)=>b-a);
    const matchScore=(matches[0]||0)+(matches[1]||0)*.72+(matches[2]||0)*.38+(matches[3]||0)*.18;
    const q5Score=q5.filter(tag=>tags.includes(tag)).length*4;
    const directQ5=flower.meaning.split('・').some(word=>q5Words.some(key=>word.includes(key)))?(answers[4]===2?25:12):0;
    const relationScore=relation.filter(tag=>tags.includes(tag)).length*3;
    const score=matchScore+q5Score+directQ5+relationScore;
    return {...flower,index,score,matched};
  }).filter(f=>eligible(f,month)).sort((a,b)=>b.score-a.score||b.matched.length-a.matched.length||a.index-b.index);
  const main=ranked[0];
  const others=[];
  // まず違う花の種類を探し、候補が不足する場合だけ色違いを許容。
  for(const f of ranked.slice(1)) {
    if(f.score<main.score*.72) break;
    if(f.name!==main.name && !others.some(x=>x.name===f.name)) others.push(f);
    if(others.length===2) break;
  }
  for(const f of ranked.slice(1)) {
    if(others.length===2) break;
    if(f.index!==main.index && !others.some(x=>x.index===f.index)) others.push(f);
  }
  return {main,others,answerScores:scores};
}
